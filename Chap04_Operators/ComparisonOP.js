// = is assignment operator
// == is loose comparison
// === is strict comparison


// > < >= <= ! !=

console.log(3 <= 4);

console.log(3 > 4);

console.log(3 == 3);

console.log(3 === "3");

console.log(3 != 4);

console.log(3 !== 4);

console.log(3 != "4");  //true  3 is int,  string //loose


console.log(3 !== "4");  //false  3 is int,  string  //strict