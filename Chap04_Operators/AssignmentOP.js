let x = 10;
x = x + 10; // x=20
x += 10; // x=30
console.log(x);

let y = 10;
y = y - 10; // y=0
y -= 10; // y=-10
console.log(y);

let z = 10;
z = z * 10; // z=100
z *= 10; // z=1000
console.log(z);

let w = 10;
w = w / 10; // w=1
w /= 10; // w=0.1
console.log(w);

let v = 10;
