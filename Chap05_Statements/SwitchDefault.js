let day = 10;

switch (day) {
    case 0: console.log("Mon"); break;

    case 1: console.log("Tue"); break;

    case 2: console.log("Wed"); break;

    case 3: console.log("Thu"); break;

    case 4: console.log("Fri"); break;

    case 5: console.log("Sat"); break

    case 6: console.log("Sun"); break

    default: console.log("Invalid day"); break



}

